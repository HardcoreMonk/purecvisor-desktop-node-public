import { createHash } from "node:crypto";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const webRoot = dirname(dirname(fileURLToPath(import.meta.url)));

// Single Edge ui-bundle 모델 (ADR-0018, pcv-single-edge-frontend-structure-v1 §4) → app.bundle.js.
// 순서표는 src/modules.json 이다. src/modules/*.ts 에 있는데 순서표에 없는 파일이 있으면 빌드가 실패한다
// (Single Edge Makefile ui-bundle 의 UI_MODULES 누락 검사와 같다). 부트스트랩은 순서표의 bootstrap 이 마지막에 붙는다.
// 빌더는 순서표 순서로 app.bundle.js 를 쓰고, sw.js 의 CACHE_NAME 을 그 바이트 hash 로 갱신한다.
const MODULE_ORDER_CONTRACT = "pcv-web-module-order-v1";
const moduleOrderPath = join(webRoot, "src/modules.json");

const paths = {
  bundle: join(webRoot, "app.bundle.js"),
  serviceWorker: join(webRoot, "sw.js")
};

const args = new Set(process.argv.slice(2));
const shouldWrite = args.has("--write");
const shouldCheck = args.has("--check");

if (shouldWrite === shouldCheck) {
  console.error("usage: node scripts/build-served-asset.mjs --write|--check");
  process.exit(2);
}

function fail(message) {
  console.error(`served asset build failed: ${message}`);
  process.exit(1);
}

function concatParts(parts) {
  return parts
    .map((part) => [
      `// --- ${part} ---`,
      readFileSync(join(webRoot, part), "utf8").trimEnd(),
      ""
    ].join("\n"))
    .join("\n");
}

function transpile(sourceText, fileName) {
  const result = ts.transpileModule(sourceText, {
    fileName,
    reportDiagnostics: true,
    compilerOptions: {
      target: ts.ScriptTarget.ES2022,
      module: ts.ModuleKind.None,
      removeComments: false,
      sourceMap: false
    }
  });
  const diagnostics = result.diagnostics ?? [];
  if (diagnostics.length > 0) {
    for (const diagnostic of diagnostics) {
      console.error(`served asset build failed: ${ts.flattenDiagnosticMessageText(diagnostic.messageText, "\n")}`);
    }
    process.exit(1);
  }
  return result.outputText.trimEnd();
}

function readModuleOrder() {
  if (!existsSync(moduleOrderPath)) fail("src/modules.json is missing");
  let order;
  try {
    order = JSON.parse(readFileSync(moduleOrderPath, "utf8"));
  } catch (error) {
    fail(`src/modules.json is not valid JSON: ${error.message}`);
  }
  if (order.contract !== MODULE_ORDER_CONTRACT) fail(`src/modules.json contract must be ${MODULE_ORDER_CONTRACT}`);
  if (!Array.isArray(order.modules) || typeof order.bootstrap !== "string") {
    fail("src/modules.json needs a modules array and a bootstrap path");
  }
  const seen = new Set();
  for (const name of order.modules) {
    if (typeof name !== "string" || !/^[a-z0-9-]+$/.test(name)) fail(`module name '${name}' must be kebab-case`);
    if (seen.has(name)) fail(`module '${name}' is listed twice`);
    seen.add(name);
  }
  const modulesDir = join(webRoot, "src/modules");
  const onDisk = existsSync(modulesDir)
    ? readdirSync(modulesDir).filter((file) => file.endsWith(".ts") && !file.endsWith(".d.ts")).map((file) => file.slice(0, -3)).sort()
    : [];
  const unlisted = onDisk.filter((name) => !seen.has(name));
  if (unlisted.length > 0) {
    fail(`src/modules/${unlisted[0]}.ts is not in src/modules.json (bundle omission, see Single Edge UI_MODULES rule); list it in order`);
  }
  const parts = order.modules.map((name) => `src/modules/${name}.ts`);
  parts.push(order.bootstrap);
  const missing = parts.find((part) => !existsSync(join(webRoot, part)));
  if (missing) fail(`${missing} is listed in src/modules.json but missing`);
  return parts;
}

function buildModuleBundle() {
  const parts = readModuleOrder();
  const sourceText = concatParts(parts);
  const sourceSha1 = createHash("sha1").update(sourceText).digest("hex").slice(0, 8);
  const outputText = transpile(sourceText, "src/app.bundle.ts");
  return [
    `// Generated from the src/modules.json order table (${MODULE_ORDER_CONTRACT}) by scripts/build-served-asset.mjs.`,
    "// Do not edit this file directly; run npm run build:served.",
    `const PCV_UI_SOURCE_SHA1 = '${sourceSha1}';`,
    outputText,
    ""
  ].join("\n");
}

// Single Edge ui-bundle 의 sw.js CACHE_NAME 자동 bump. sw.js 가 생기는 Task 15 전에는 아무것도 하지 않는다.
function serviceWorkerText(bundleText) {
  if (!existsSync(paths.serviceWorker)) return null;
  const current = readFileSync(paths.serviceWorker, "utf8");
  const precacheInputs = ["index.html", "style.css", "i18n.js", "offline.html", "manifest.json"]
    .filter((file) => existsSync(join(webRoot, file)))
    .map((file) => readFileSync(join(webRoot, file), "utf8").replace(/\r\n/g, "\n"));
  // Hash LF-normalized text so a CRLF working copy on Windows and the LF checkout on Linux CI agree on the name.
  const hash = createHash("sha1").update([bundleText.replace(/\r\n/g, "\n"), ...precacheInputs].join("\n")).digest("hex").slice(0, 8);
  const next = current.replace(/const CACHE_NAME = 'pcv-ui-v[^']*';/, `const CACHE_NAME = 'pcv-ui-v${hash}';`);
  return { current, next };
}

const nextBundle = buildModuleBundle();
const serviceWorker = serviceWorkerText(nextBundle);

if (shouldWrite) {
  writeFileSync(paths.bundle, nextBundle, "utf8");
  if (serviceWorker && serviceWorker.current !== serviceWorker.next) {
    writeFileSync(paths.serviceWorker, serviceWorker.next, "utf8");
    console.log("sw.js CACHE_NAME bumped");
  }
  console.log("served app.bundle.js regenerated from the src/modules.json order table");
} else {
  if (!existsSync(paths.bundle)) fail("app.bundle.js is missing; run npm run build:served");
  if (readFileSync(paths.bundle, "utf8") !== nextBundle) {
    console.error("served asset verification failed: committed app.bundle.js is stale; run npm run build:served");
    process.exit(1);
  }
  if (serviceWorker && serviceWorker.current !== serviceWorker.next) {
    console.error("served asset verification failed: sw.js CACHE_NAME is stale; run npm run build:served");
    process.exit(1);
  }
  console.log("served app.bundle.js is current");
}

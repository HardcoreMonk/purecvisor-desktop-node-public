import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const webRoot = dirname(dirname(fileURLToPath(import.meta.url)));

// 순서는 원본 src/served-app.ts 의 선언 순서를 그대로 따른다. 연결 후 한 스코프이고 function
// 선언은 호이스팅되므로 순서가 동작을 정하지는 않지만, 원본 순서를 유지해야 분해 전후 app.js 를
// 대조하기 쉽다. src/served-app.ts 는 마지막에 둔다 — 유일한 최상위 실행문
// (document.addEventListener('DOMContentLoaded', init)) 이 그 파일 끝에 있다.
const servedSourceParts = [
  "src/served/types.ts",
  "src/served/state.ts",
  "src/served/routes.ts",
  "src/served/errors.ts",
  "src/served/api-client.ts",
  "src/served/evidence.ts",
  "src/served/summary.ts",
  "src/served/table.ts",
  "src/served/rbac.ts",
  "src/served/render-ops.ts",
  "src/served/render-inventory.ts",
  "src/served/render-qos.ts",
  "src/served/render-vm-detail.ts",
  "src/served/render-jobs.ts",
  "src/served/render-monitoring.ts",
  "src/served/render-panels.ts",
  "src/served/render-console.ts",
  "src/served/render-activity.ts",
  "src/served/render-shell.ts",
  "src/served/load.ts",
  "src/served/mutate.ts",
  "src/served/job-polling.ts",
  "src/served/actions.ts",
  "src/served-app.ts"
];

const paths = {
  output: join(webRoot, "app.js")
};

const args = new Set(process.argv.slice(2));
const shouldWrite = args.has("--write");
const shouldCheck = args.has("--check");

if (shouldWrite === shouldCheck) {
  console.error("usage: node scripts/build-served-asset.mjs --write|--check");
  process.exit(2);
}

function buildServedAsset() {
  const missingPart = servedSourceParts.find((part) => !existsSync(join(webRoot, part)));
  if (missingPart) {
    console.error(`served asset build failed: ${missingPart} is missing`);
    process.exit(1);
  }

  const sourceText = servedSourceParts
    .map((part) => [
      `// --- ${part} ---`,
      readFileSync(join(webRoot, part), "utf8").trimEnd(),
      ""
    ].join("\n"))
    .join("\n");
  const result = ts.transpileModule(sourceText, {
    fileName: "src/served-app.bundle.ts",
    reportDiagnostics: true,
    compilerOptions: {
      target: ts.ScriptTarget.ES2022,
      module: ts.ModuleKind.None,
      removeComments: false,
      sourceMap: false
    }
  });

  const diagnostics = result.diagnostics ?? [];
  if (diagnostics.length > 0) {
    for (const diagnostic of diagnostics) {
      const message = ts.flattenDiagnosticMessageText(diagnostic.messageText, "\n");
      console.error(`served asset build failed: ${message}`);
    }
    process.exit(1);
  }

  return [
    "// Generated from staged src/served source parts by scripts/build-served-asset.mjs.",
    "// Do not edit this file directly; run npm run build:served.",
    result.outputText.trimEnd(),
    ""
  ].join("\n");
}

const nextText = buildServedAsset();

if (shouldWrite) {
  writeFileSync(paths.output, nextText, "utf8");
  console.log("served app.js regenerated from TypeScript");
} else {
  if (!existsSync(paths.output)) {
    console.error("served asset verification failed: app.js is missing");
    process.exit(1);
  }

  const currentText = readFileSync(paths.output, "utf8");
  if (currentText !== nextText) {
    console.error("served asset verification failed: committed app.js is stale; run npm run build:served");
    process.exit(1);
  }

  console.log("served app.js is current");
}
